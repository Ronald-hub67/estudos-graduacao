public class Produto {
    private String nome;
    private int estoque;

    public String getNome(){
        return this.nome;
    }
    public void setNome(String nome){
        this.nome = nome;
    }
    public int getEstoque(){
        return this.estoque;
    }
    public void setEstoque(int estoque) {
        this.estoque = estoque;
    }
}